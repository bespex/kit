// From themes and recipes to one stylesheet (dist/sx.css). An app sets two kinds of attributes on <html>
// (or on any element, theme and style together):
//   data-sx-theme="fjord"                    the colour theme; "auto" follows light/dark of the system
//   data-sx-shape="round" data-sx-chrome="raised" …   one per style axis; a missing one takes "calm"
// and marks its zones with the classes `sx-chrome`, `sx-emphasis`, `sx-area` (style.ts).

import { derive } from "./derive.js";
import { cssValue, DEFAULT_STYLE, RECIPES, ZONE_ROLES, type Value } from "./style.js";
import { AXES, type Axis, type ColorTheme } from "./types.js";

const block = (selector: string, decls: [string, string][]) =>
  `${selector} {\n${decls.map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`;

/** The variables of one theme: `--sx-<role>`, and `color-scheme`. */
export function themeDecls(t: ColorTheme): [string, string][] {
  const r = derive(t);
  const decls: [string, string][] = [["color-scheme", r.scheme]];
  for (const [k, v] of Object.entries(r)) decls.push([`--sx-${k}`, v]);
  return decls;
}

const stepDecls = (step: Record<string, Value>): [string, string][] =>
  Object.entries(step).map(([k, v]) => [`--sx-${k}`, cssValue(v)]);

/** The whole stylesheet: all themes, the defaults, every step of every axis, the zones. */
export function stylesheet(themes: ColorTheme[], auto: { light: string; dark: string }): string {
  const byId = (id: string) => themes.find((t) => t.id === id)!;
  const out: string[] = ["/* Generated by tools/build.mjs from themes/colors and themes/src. Do not edit. */\n"];

  // Themes. "auto" (and a page that names none) follows the system: light and dark of the set.
  out.push(block(':root,\n[data-sx-theme="auto"]', themeDecls(byId(auto.light))));
  out.push(`@media (prefers-color-scheme: dark) {\n${block('  :root,\n  [data-sx-theme="auto"]', themeDecls(byId(auto.dark)))}}\n`);
  for (const t of themes) out.push(block(`[data-sx-theme="${t.id}"]`, themeDecls(t)));

  // Style: the default step of each axis on every themed element, so a theme nested in another starts
  // from the defaults; then each step for the element that names it
  const defaults: [string, string][] = [];
  for (const axis of Object.keys(AXES) as Axis[]) defaults.push(...stepDecls(full(axis, DEFAULT_STYLE[axis])));
  out.push(block(":root,\n[data-sx-theme]", defaults));
  for (const axis of Object.keys(AXES) as Axis[])
    for (const step of AXES[axis]) out.push(block(`[data-sx-${axis}="${step}"]`, stepDecls(full(axis, step))));

  // Zones
  const rebind = (prefix: string) => ZONE_ROLES.map((r) => [`--sx-${r}`, `var(--sx-${prefix}-${r})`] as [string, string]);
  out.push(block(":where(.sx-chrome)", [...rebind("chrome"), ["color-scheme", "var(--sx-chrome-scheme)"], ["color", "var(--sx-ink)"], ["background-color", "var(--sx-bg)"]]));
  out.push(block(":where(.sx-emphasis)", [...rebind("emph"), ["color-scheme", "var(--sx-emph-scheme)"], ["color", "var(--sx-ink)"], ["background-color", "var(--sx-bg)"]]));
  for (let k = 1; k <= 4; k++)
    out.push(block(`:where(.sx-area[data-area="${k}"])`, [
      ...["bg", "panel", "surface"].map((r) => [`--sx-${r}`, `var(--sx-area-${k}-bg)`] as [string, string]),
      ...["ink", "ink-2", "ink-3"].map((r) => [`--sx-${r}`, `var(--sx-area-${r})`] as [string, string]),
      ["color-scheme", "var(--sx-area-scheme)"], ["color", "var(--sx-ink)"], ["background-color", "var(--sx-bg)"],
    ]));

  out.push(`@media (prefers-reduced-motion: reduce) {\n${block("  :root,\n  [data-sx-theme]", [["--sx-duration", "0ms !important"]])}}\n`);
  return out.join("\n");
}

/** A step with everything the default step of its axis sets, so that steps can stay short. */
function full(axis: Axis, step: string): Record<string, Value> {
  const table = RECIPES[axis] as Record<string, Record<string, Value>>;
  return { ...table[DEFAULT_STYLE[axis] as string], ...table[step] };
}
