// Builds themes/dist from themes/colors, themes/styles and themes/src:
//   1. themes/src/data.gen.ts  the themes and styles in the order the pickers offer them
//   2. tsc                      themes/dist/*.js and *.d.ts
//   3. themes/dist/sx.css       every theme, every step of every axis, the zones
// dist is checked in, so apps install the package without building it.
//
//   npm run build

import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const themes = join(root, "themes");

/** The order in the pickers, four in a row after "auto": the light themes, then the dark ones. */
const THEME_ORDER = ["paper", "frost", "ink", "colorful", "graphite", "fjord", "forest", "moon", "elegance", "neon", "terminal"];
const STYLE_ORDER = ["tool", "calm", "stage"];
const AUTO = { light: "paper", dark: "graphite" };

const load = (dir, order) => {
  const all = readdirSync(join(themes, dir)).filter((f) => f.endsWith(".json")).map((f) => JSON.parse(readFileSync(join(themes, dir, f), "utf8")));
  const rank = (id) => (order.indexOf(id) < 0 ? order.length : order.indexOf(id));
  return all.sort((a, b) => rank(a.id) - rank(b.id) || a.id.localeCompare(b.id));
};

const colors = load("colors", THEME_ORDER);
const styles = load("styles", STYLE_ORDER);
writeFileSync(
  join(themes, "src/data.gen.ts"),
  `// Generated by tools/build.mjs from themes/colors and themes/styles. Do not edit.\n\n` +
    `import type { ColorTheme, StylePreset } from "./types.js";\n\n` +
    `export const THEMES: ColorTheme[] = ${JSON.stringify(colors)};\n\n` +
    `export const STYLES: StylePreset[] = ${JSON.stringify(styles)};\n\n` +
    `/** What the theme "auto" shows in a light and in a dark system. */\n` +
    `export const AUTO = ${JSON.stringify(AUTO)};\n`,
);

execFileSync(join(root, "node_modules/.bin/tsc"), ["-p", root], { stdio: "inherit" });

const { stylesheet } = await import(join(themes, "dist/css.js") + `?t=${Date.now()}`);
writeFileSync(join(themes, "dist/sx.css"), stylesheet(colors, AUTO));
console.log(`built: ${colors.length} themes, ${styles.length} styles`);
